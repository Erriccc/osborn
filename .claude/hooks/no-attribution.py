#!/usr/bin/env python3
"""PreToolUse guard: no session link or AI attribution in anything written to
GitHub (commits, PRs, issues, comments, reviews). Founder's standing rule (see CLAUDE.md,
"Attribution rules"). Reads the hook payload on stdin; prints a deny decision
when it matches, nothing otherwise. Fails open on any parse error."""
import json, re, sys

SESSION = re.compile(r"claude\.ai/code/session_|^\s*Claude-Session\s*:", re.I | re.M)
CREDIT = re.compile(
    r"^\s*Co-Authored-By\s*:.*(claude|anthropic)|Generated (with|by) \[?Claude", re.I | re.M
)

# A credit line on its own (the footer), not a sentence that mentions Claude.
FOOTER = re.compile(r"^[ \t]*(?:-{3,}[ \t]*\n[ \t]*)?_?(?:\U0001F916[ \t]*)?Generated (?:with|by) \[?Claude[^\n]*$\n?", re.I | re.M)

def deny(reason):
    print(json.dumps({"hookSpecificOutput": {
        "hookEventName": "PreToolUse",
        "permissionDecision": "deny",
        "permissionDecisionReason": reason,
    }}))
    sys.exit(0)

try:
    payload = json.load(sys.stdin)
except Exception:
    sys.exit(0)

tool = payload.get("tool_name", "")
inp = payload.get("tool_input") or {}

# Bash commits are not touched here: .githooks/commit-msg strips credit lines
# from every commit message at the git level. Rewriting the command here would
# also need an "allow" decision, which would skip the permission check for
# whatever else the command does.
if tool.startswith("mcp__github__"):
    text = "\n".join(str(inp.get(k, "")) for k in ("body", "title", "message", "commit_message"))
    # Merges, pushes and file writes: refuse (stripping would need an "allow"
    # that skips the user's permission prompt for the merge or push itself).
    if re.search(r"push_files|create_or_update_file|merge", tool):
        if SESSION.search(text) or CREDIT.search(text):
            deny("Blocked by repo rule: no session links or AI attribution in commits (CLAUDE.md, Attribution rules).")
    # PR titles and descriptions: strip it, so the call goes through clean.
    elif re.search(r"(create|update)_pull_request", tool):
        if SESSION.search(text) or CREDIT.search(text):
            # Whole lines only: a sentence that mentions "generated by Claude" mid-line is kept.
            clean = {}
            for k in ("body", "title", "message", "commit_message"):
                v = inp.get(k)
                if not isinstance(v, str):
                    continue
                v = FOOTER.sub("", v)
                v = re.sub(r"^\s*(Co-Authored-By\s*:.*(claude|anthropic).*|Claude-Session\s*:.*)$\n?", "", v, flags=re.I | re.M)
                v = re.sub(r"\S*claude\.ai/code/session_\S*", "", v)
                clean[k] = v.rstrip()
            print(json.dumps({"hookSpecificOutput": {"hookEventName": "PreToolUse", "permissionDecision": "allow",
                              "updatedInput": {**inp, **clean},
                              "permissionDecisionReason": "Attribution stripped (CLAUDE.md, Attribution rules)."}}))
            sys.exit(0)
    # Everything else posted to GitHub (comments, issues, reviews): never a
    # session link or a credit footer.
    elif SESSION.search(text) or FOOTER.search(text) or re.search(r"^\s*Co-Authored-By\s*:.*(claude|anthropic)", text, re.I | re.M):
        deny("Blocked by repo rule: no AI credit footer or session link in anything posted to GitHub, "
             "comments included. Remove the 'Generated by Claude Code' line and post again (CLAUDE.md, Attribution rules).")
sys.exit(0)
