/**
 * modelBadge.ts — pure helpers that turn the REAL signals the frontend already
 * receives into a model/provider badge descriptor (issue #87).
 *
 * Why this exists: the agent's PROSE self-report of its own model is unreliable —
 * live QA caught one reply claiming both "OpenAI GPT-4 Turbo" (its quick take)
 * and "Anthropic Claude Opus 5.5" (its final answer). The badge is therefore
 * driven ONLY by signals the server emits, never by what the agent says about
 * itself in the reply text:
 *
 *   - main-brain provider  ← agent_ready.provider          (server-declared, e.g. 'claude')
 *   - osborn version       ← GET /health → { version }     (already polled in VoiceRoom)
 *   - fast-brain quick take ← fast_brain_response.agentRole (=== 'pipeline-fast-brain')
 *
 * The fast brain's EXACT provider name (Fireworks / OpenRouter / z.ai) is resolved
 * server-side in agent/src/pipeline-fastbrain.ts but is NOT yet on the wire, so a
 * quick take is labelled generically ("⚡ Fast brain") until an agent-side emit adds
 * a `provider` field to `fast_brain_response` (tracked as the #87 follow-up).
 *
 * Rule: never invent a model name. An unrecognised-but-present signal falls back to
 * its RAW value (that is still what the data said); an absent signal → neutral state.
 */

/** Resolved header badge, ready to render. */
export interface ModelBadgeView {
  /** Short pill label, e.g. "Claude". Null → caller renders the neutral state. */
  label: string | null
  /** Osborn release string if known, e.g. "0.9.275" (no leading 'v'). */
  version: string | null
  /** Full tooltip / aria description. */
  title: string
  /** False until a provider signal arrives — caller shows a neutral pill. */
  known: boolean
}

// Known provider keys → display labels (case-insensitive lookup). Extend as more
// providers gain an on-the-wire identity. A present-but-unlisted value is shown
// verbatim rather than dropped, so the badge never hides a real signal.
const PROVIDER_LABELS: Record<string, string> = {
  claude: 'Claude',
  anthropic: 'Claude',
  zai: 'z.ai GLM',
  'z.ai': 'z.ai GLM',
  fireworks: 'Fireworks',
  openrouter: 'OpenRouter',
  openai: 'OpenAI',
  gemini: 'Gemini',
  google: 'Gemini',
}

/**
 * Map a raw provider signal to a human label.
 *   - blank / non-string      → null (no signal)
 *   - recognised key          → its display label (case-insensitive)
 *   - present but unrecognised → the trimmed raw value (faithful, never a guess)
 */
export function providerLabel(provider: unknown): string | null {
  if (typeof provider !== 'string') return null
  const raw = provider.trim()
  if (!raw) return null
  return PROVIDER_LABELS[raw.toLowerCase()] ?? raw
}

/** Normalise a version string: trim, strip a leading 'v'; blank/non-string → null. */
export function normalizeVersion(v: unknown): string | null {
  if (typeof v !== 'string') return null
  const s = v.trim().replace(/^v/i, '')
  return s || null
}

export interface ModelBadgeInput {
  /** agent_ready.provider — the main brain's server-declared provider. */
  mainProvider?: unknown
  /** /health → version — the running osborn release. */
  version?: unknown
  /** Whether the agent session is connected (agent_ready seen). */
  connected?: boolean
}

/**
 * Resolve the header model badge from the real signals. Surfaces the authoritative
 * main-brain provider (+ osborn version when known). Never guesses: an absent or
 * unrecognised-as-blank provider → neutral state rather than a fabricated name.
 */
export function resolveModelBadge(input: ModelBadgeInput): ModelBadgeView {
  const label = providerLabel(input.mainProvider)
  const version = normalizeVersion(input.version)
  if (label) {
    const vSuffix = version ? ` · Osborn ${version}` : ''
    return {
      label,
      version,
      known: true,
      title:
        `Answers are generated by ${label}${vSuffix}. This is the session's declared ` +
        `model provider (reported by the agent runtime, not parsed from the reply text). ` +
        `Provisional ⚡ quick takes are drafted by a separate fast brain.`,
    }
  }
  return {
    label: null,
    version,
    known: false,
    title: input.connected
      ? 'The answering model has not reported its provider yet.'
      : 'Connecting to the agent…',
  }
}

/**
 * Label for a fast-brain (quick-take) reply. Prefers an explicit provider if the
 * agent ever sets `fast_brain_response.provider` (the #87 follow-up emit); until
 * then the `agentRole` alone identifies it as the separate fast brain.
 */
export function fastBrainLabel(opts: { provider?: unknown; agentRole?: unknown }): string {
  const p = providerLabel(opts.provider)
  if (p) return `⚡ ${p}`
  if (typeof opts.agentRole === 'string' && /fast[-_ ]?brain/i.test(opts.agentRole)) {
    return '⚡ Fast brain'
  }
  return '⚡ Quick take'
}
